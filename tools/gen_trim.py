#!/usr/bin/env python3
"""Generates machines/metal/trim.h: how much to turn the voice down for each setting of the four knobs, so that a
strike's first peaks stay under the output ceiling instead of being clipped there. Run from the repository root, with
the SDK beside it (../open-xy):

    python3 tools/gen_trim.py [--jobs 2] [--peaks FILE] [--save-peaks FILE]

It builds the engine on the host without its trim (a zero table) and with its output ceiling taken off, strikes a note
from silence at every setting of the grid below and at every second note from C1 to C7, and keeps each setting's
loudest peak over those notes, in dB against the ceiling. A setting needs turning down by that peak plus MARGIN_DB
when that is above 0, in steps of UNIT_DB rounded up; the table holds that for each of its nodes, which are the settings
measured, and engine.cpp (trim_for) interpolates between them. Measuring takes about forty minutes on two cores;
--peaks reuses a saved measurement and measures only the settings it lacks.
"""
import argparse
import math
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MACHINE = ROOT / 'machines' / 'metal'
SDK = ROOT.parent / 'open-xy'

MARGIN_DB = 0.5                         # under the ceiling, for notes and settings between those measured
UNIT_DB = 0.4                           # the table's unit: four bits a node, so up to 6 dB
NOTES = range(24, 97, 2)                # C1 .. C7, every second note
BLOCKS = 207                            # 0.3 s: the loud part of a note is its first 50 ms
# The table's nodes over each knob (0..99 as the OP-XY shows it).
AXES = {
    'D': [3 * i for i in range(34)],    # 0, 3, .. 99
    'R': [3 * i for i in range(34)],
    'S': [11 * i for i in range(10)],   # 0, 11, .. 99
    'M': [11 * i for i in range(10)],
}
# Each node takes the most that any measured setting this many nodes either side of it needs, in each axis: the peaks
# move faster between nodes than interpolating between them follows, so a node covers its neighbours' too.
REACH = {'D': 1, 'R': 1, 'S': 1, 'M': 1}

MAPPER = r'''
#include "engine_peak.cpp"
#include <cmath>
#include <cstdio>
// Settings on stdin as "d r s m" (knob positions, 0..99); prints each with its loudest peak over the notes, dB.
int main(int argc, char** argv) {
    static metal::Voice voice; static metal::Shared shared;
    opxy::u32 pitch[64]; opxy::i32 out[64];
    int k[4];
    while (std::scanf("%d %d %d %d", &k[0], &k[1], &k[2], &k[3]) == 4) {
        opxy::i32 parameters[8] = {0};
        for (int i = 0; i < 4; ++i) parameters[i] = static_cast<opxy::i32>(k[i] / 99.0 * 2147483647.0);
        double worst = -99;
        for (int note = @N0@; note <= @N1@; note += @DN@) {
            const opxy::u32 inc = static_cast<opxy::u32>(440.0 * std::exp2((note - 69) / 12.0) / 44100.0 * 4294967296.0);
            for (int i = 0; i < 64; ++i) pitch[i] = inc;
            metal::initialize(voice, shared, 1);
            metal::start(voice, shared, 1);
            g_peak = 0;
            for (int b = 0; b < @BLOCKS@; ++b) metal::render(voice, shared, 1, out, parameters, pitch);
            const double db = 20 * std::log10(g_peak / 536870912.0);
            if (db > worst) worst = db;
        }
        std::printf("%d %d %d %d %.3f\n", k[0], k[1], k[2], k[3], worst);
        std::fflush(stdout);
    }
}
'''


def header(table):
    dims = [len(AXES[a]) for a in 'DRSM']
    lines = ['// Generated by tools/gen_trim.py. Do not edit.',
             '// How far to turn the voice down for each setting of the knobs, so that a strike stays under the ceiling:',
             '// units of %g dB, four bits each (two to a byte, the first in the low four), over DROP, RATIO, STRETCH'
             % UNIT_DB, '// and MODES at the nodes below (of 0..99 as the OP-XY shows them).',
             '#pragma once', '#include <opxy/types.hpp>', 'namespace metal {']
    lines.append('const opxy::i32 TRIM_D = %d, TRIM_R = %d, TRIM_S = %d, TRIM_M = %d;' % tuple(dims))
    # Each axis: node position = knob word (Q31) >> 15 times its scale (Q8), giving Q16 nodes.
    for a in 'DRSM':
        scale = (len(AXES[a]) - 1)
        assert AXES[a] == [round(99 * i / scale) for i in range(scale + 1)] or AXES[a][-1] == 99, a
        lines.append('const opxy::i32 TRIM_%s_SCALE = %d;   // nodes over the knob, Q8 (%d nodes, 0..99)'
                     % (a, scale * 256, len(AXES[a])))
    lines.append('const opxy::i32 TRIM_UNIT_LOG = %d;   // log2 of %g dB, Q24' % (round(UNIT_DB / 20 * math.log2(10) * (1 << 24)), UNIT_DB))
    flat = [v for d in table for r in d for s in r for v in s]
    flat += [0] * (len(flat) % 2)
    packed = [flat[i] | flat[i + 1] << 4 for i in range(0, len(flat), 2)]
    lines.append('const unsigned char TRIM[%d] = {' % len(packed))
    for i in range(0, len(packed), 32):
        lines.append('    ' + ', '.join(str(v) for v in packed[i:i + 32]) + ',')
    lines.append('};')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def zero_table():
    return [[[[0] * len(AXES['M']) for _ in AXES['S']] for _ in AXES['R']] for _ in AXES['D']]


def measure(points, jobs):
    with tempfile.TemporaryDirectory(prefix='metal-trim-') as tmp:
        tmp = Path(tmp)
        for f in MACHINE.glob('*.h'):
            shutil.copy(f, tmp)
        (tmp / 'trim.h').write_text(header(zero_table()))           # no trim while measuring
        src = (MACHINE / 'engine.cpp').read_text()
        for old, new in [
            ('buf[n] = clamp(e, -(1 << 30), 1 << 30) >> 1;', 'buf[n] = e >> 1;'),   # no ceiling: the peaks as they are
            ('            output[2 * n] = ceiling2(u0);',
             '            { const i32 m0 = u0 < 0 ? -u0 : u0, m1 = u1 < 0 ? -u1 : u1;\n'
             '              if (m0 > g_peak) g_peak = m0; if (m1 > g_peak) g_peak = m1; }\n'
             '            output[2 * n] = ceiling2(u0);')]:
            assert old in src, old
            src = src.replace(old, new)
        (tmp / 'engine_peak.cpp').write_text('#include <opxy/types.hpp>\nstatic int g_peak = 0;\n' + src)
        notes = list(NOTES)
        (tmp / 'mapper.cpp').write_text(MAPPER.replace('@N0@', str(notes[0])).replace('@N1@', str(notes[-1]))
                                        .replace('@DN@', str(notes[1] - notes[0])).replace('@BLOCKS@', str(BLOCKS)))
        subprocess.run(['c++', '-O2', '-std=c++11', '-I', str(SDK / 'sdk' / 'include'), '-I', str(tmp),
                        '-o', str(tmp / 'mapper'), str(tmp / 'mapper.cpp')], check=True)
        chunks = [points[i::jobs] for i in range(jobs)]
        procs = [subprocess.Popen([str(tmp / 'mapper')], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)
                 for _ in chunks]
        outs = [p.communicate('\n'.join('%d %d %d %d' % q for q in c) + '\n') for p, c in zip(procs, chunks)]
        peaks = {}
        for out, _ in outs:
            for line in out.split('\n'):
                if line.strip():
                    d, r, s, m, db = line.split()
                    peaks[(int(d), int(r), int(s), int(m))] = float(db)
        return peaks


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--jobs', type=int, default=2)
    p.add_argument('--peaks', help='reuse peaks saved by --save-peaks instead of measuring')
    p.add_argument('--save-peaks')
    args = p.parse_args()
    points = [(d, r, s, m) for d in AXES['D'] for r in AXES['R'] for s in AXES['S'] for m in AXES['M']]
    peaks = {}
    if args.peaks:
        for line in Path(args.peaks).read_text().split('\n'):
            if line.strip():
                d, r, s, m, db = line.split()
                peaks[(int(d), int(r), int(s), int(m))] = float(db)
    missing = [q for q in points if q not in peaks]
    if missing:
        print('measuring %d settings' % len(missing))
        peaks.update(measure(missing, args.jobs))
    if args.save_peaks:
        Path(args.save_peaks).write_text(''.join('%d %d %d %d %.3f\n' % (k + (v,)) for k, v in sorted(peaks.items())))
    need = {k: max(0.0, v + MARGIN_DB) for k, v in peaks.items()}
    def around(axis, i):
        return range(max(0, i - REACH[axis]), min(len(AXES[axis]), i + REACH[axis] + 1))
    table = zero_table()
    for di, d in enumerate(AXES['D']):
        for ri, r in enumerate(AXES['R']):
            for si, st in enumerate(AXES['S']):
                for mi, m in enumerate(AXES['M']):
                    most = max(need[(AXES['D'][a], AXES['R'][b], AXES['S'][c], AXES['M'][e])]
                               for a in around('D', di) for b in around('R', ri)
                               for c in around('S', si) for e in around('M', mi))
                    units = math.ceil(most / UNIT_DB - 1e-9)
                    assert units <= 15, 'a node needs more than 15 units: %s' % ((d, r, st, m),)
                    table[di][ri][si][mi] = units
    (MACHINE / 'trim.h').write_text(header(table))
    hot = sum(1 for q in points if peaks[q] > -MARGIN_DB)
    print('trim.h written: %d of %d settings need turning down, by at most %.2f dB'
          % (hot, len(points), max(need[q] for q in points)))


if __name__ == '__main__':
    sys.exit(main())
